const createLessons = ({
  language,
  alphabetGroups,
  vowels,
  consonantGroups,
  distinctiveLetters,
  letterPairs,
  soundLessons,
  vocabulary,
  synonyms,
  antonyms,
  reviews,
}) => {
  const lessons = [
    {
      category: 'Getting started',
      title: `Meet ${language}`,
      phrase: language,
      translation: 'Listen carefully, repeat a sound, and notice how sounds join to make words.',
      objective: 'Listen, repeat, and get ready to explore the sounds of this language.',
    },
    ...alphabetGroups.map((group, index) => ({
      category: 'Alphabet and writing',
      title: `Alphabet group ${index + 1}`,
      phrase: group.letters,
      translation: group.note,
      objective: `Say each letter in order. ${group.note}`,
    })),
    ...vowels.map((vowel, index) => ({
      category: 'Vowel sounds',
      title: `Vowel sound ${index + 1}: ${vowel.label}`,
      phrase: vowel.phrase,
      translation: vowel.note,
      objective: `Listen for ${vowel.label}, then say the example slowly.`,
    })),
    {
      category: 'Vowel sounds',
      title: 'Vowels in a word',
      phrase: vowels.map(({ label }) => label).join(', '),
      translation: 'Find and say the vowel sounds you hear at the beginning, middle, or end of a word.',
      objective: 'Notice where a vowel sound appears in a spoken word.',
    },
    {
      category: 'Vowel sounds',
      title: 'Vowel review',
      phrase: vowels.map(({ phrase }) => phrase).join(' · '),
      translation: 'Review the vowel sounds for this language. Some languages also use marks or vowel length.',
      objective: 'Repeat the vowel sounds and listen for the differences.',
    },
    ...consonantGroups.map((group, index) => ({
      category: 'Consonant sounds',
      title: `Consonant group ${index + 1}`,
      phrase: group.letters,
      translation: group.note,
      objective: `Say each consonant clearly. ${group.note}`,
    })),
    {
      category: 'Consonant sounds',
      title: 'Distinctive consonants',
      phrase: distinctiveLetters.phrase,
      translation: distinctiveLetters.note,
      objective: `Listen for the consonants that are especially important in ${language}.`,
    },
    {
      category: 'Consonant sounds',
      title: 'Letter pairs and combined sounds',
      phrase: letterPairs.phrase,
      translation: letterPairs.note,
      objective: 'Listen to each pair and notice whether it makes a sound of its own.',
    },
    {
      category: 'Consonant sounds',
      title: 'Consonant review',
      phrase: consonantGroups.map(({ letters }) => letters).join(' · '),
      translation: 'Review the consonant groups. Notice how the mouth starts or shapes each sound.',
      objective: 'Repeat the consonants slowly, then say them at a natural pace.',
    },
    ...soundLessons.map((sound) => ({
      category: sound.category,
      title: sound.title,
      phrase: sound.phrase,
      translation: sound.note,
      objective: sound.objective,
    })),
    ...vocabulary.map((word) => ({
      category: 'First words',
      title: word.title,
      phrase: word.phrase,
      translation: word.translation,
      objective: `Listen, repeat, and connect “${word.translation}” with its ${language} word.`,
    })),
    ...synonyms.map((pair, index) => ({
      category: 'Words with similar meanings',
      title: `Synonyms ${index + 1}: ${pair.meaning}`,
      phrase: pair.phrase,
      translation: pair.note,
      objective: `Listen to the two ${language} words and compare their similar meanings.`,
    })),
    ...antonyms.map((pair, index) => ({
      category: 'Opposite meanings',
      title: `Antonyms ${index + 1}: ${pair.meaning}`,
      phrase: pair.phrase,
      translation: pair.note,
      objective: `Say both ${language} words and notice how their meanings are opposite.`,
    })),
    ...reviews.map((review) => ({
      category: 'Practice and review',
      title: review.title,
      phrase: review.phrase,
      translation: review.note,
      objective: review.objective,
    })),
  ];

  if (lessons.length !== 50) {
    throw new Error(`${language} Kindergarten curriculum must contain exactly 50 lessons.`);
  }

  return Object.freeze(lessons.map((lesson, index) => Object.freeze({
    id: index + 1,
    ...lesson,
    phonetic: '',
    syllables: Object.freeze([]),
  })));
};

